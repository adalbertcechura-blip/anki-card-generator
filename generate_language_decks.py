def _make_card(cid, title, cat, prompt, trans, extra_lbl, extra_val, example):
    front = f"{prompt}\n*({cat})*"
    back = f"**Kategorie:** {cat}\n**Překlad:** {trans}\n**{extra_lbl}:** {extra_val}"
    if example:
        back += f"\n**Příklad:** {example}"
    return {
        "id": cid,
        "title": title,
        "f": front,
        "b": back,
        "a": trans.split(",")[0].split(";")[0].strip(),
    }


